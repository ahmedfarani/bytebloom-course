/*
    What is a Design Pattern?

    - A reusable, well-tested solution to a common problem within a given context.
    - It's not a finished piece of code, but a template or a description of how to solve a problem.
    - Think of it like a recipe: it tells you the ingredients and the steps, but you still have to cook the

    Why use them?

    1.  SOLUTIONS: They provide proven solutions to common challenges, saving you time and effort.
    2.  VOCABULARY: They create a shared language for developers. Saying "Let's use a Factory here" is
        much faster than explaining the whole concept from scratch.
    3.  STRUCTURE: They lead to well-organized, maintainable, and flexible code.

    Three Main Categories of Patterns:

    1.  Creational Patterns:
        - Deal with the process of object creation.
        - They help make a system independent of how its objects are created, composed, and represented.
        - Example: The Factory Pattern (which we'll see next!).

    2.  Structural Patterns:
        - Deal with how classes and objects are composed to form larger structures.
        - Example: The Decorator Pattern (we'll see this later).

    3.  Behavioral Patterns:
        - Deal with communication between objects.
        - Example: The Observer and Strategy Patterns (we'll see these later).

    In the next lesson, we will implement our first pattern to solve a common creation problem.
*/




